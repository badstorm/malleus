//! The byte budget of a DeepSeek-V4.1 file under a precision map (issue #83).
//!
//! The map itself lives in `malleus-gguf` so the converter can read it without the model crate's kernels; this
//! module only walks the tensor map and adds the bytes up.

use crate::deepseek::Expect;
use malleus_gguf::DType;
pub use malleus_gguf::deepseek_alloc::*;

/// One row of the byte inventory: a class of tensors, how many, and how many bytes they take.
#[derive(Debug, Clone)]
pub struct ClassBytes {
    pub class: &'static str,
    pub tensors: usize,
    pub bytes: u64,
}

/// The file's byte inventory under an allocation, per class.
pub fn budget(expects: &[Expect], alloc: &Allocation) -> Vec<ClassBytes> {
    let mut out: Vec<ClassBytes> = Vec::new();
    for e in expects {
        let key = allocation_key(&e.name);
        let pick = alloc.pick(&key);
        // A scale tensor is regenerated by the quantizer, so the checkpoint's own is not in the file.
        if let Some(weight) = e.name.strip_suffix(".scale")
            && alloc.pick(&allocation_key(weight)) != Pick::Keep
        {
            continue;
        }
        // The routed experts keep their fp4 pairs in an I8 tensor: the shape counts pairs, not values.
        let packed = e.dtype == DType::I8 && e.class == "experts";
        let bytes = tensor_bytes(pick, e.dtype, &e.shape, packed);
        match out.iter_mut().find(|c| c.class == e.class) {
            Some(c) => {
                c.tensors += 1;
                c.bytes += bytes;
            }
            None => out.push(ClassBytes {
                class: e.class,
                tensors: 1,
                bytes,
            }),
        }
    }
    out.sort_by_key(|c| std::cmp::Reverse(c.bytes));
    out
}

#[cfg(test)]
mod budget_report {
    use super::*;
    use crate::config::Config;

    /// Prints the file's byte inventory under the published allocation. Run with the checkpoint's directory
    /// and the allocation text:
    ///
    ///   DEEPSEEK_CKPT=/models/deepseekv41-flash DEEPSEEK_ALLOC=/tmp/alloc.txt \
    ///     cargo test -p malleus-model budget_report -- --ignored --nocapture
    #[test]
    #[ignore = "reads the checkpoint's config and the published allocation"]
    fn the_file_budget_under_the_published_allocation() {
        let ckpt = std::env::var("DEEPSEEK_CKPT").expect("DEEPSEEK_CKPT");
        let alloc_path = std::env::var("DEEPSEEK_ALLOC").expect("DEEPSEEK_ALLOC");
        let text = std::fs::read_to_string(&alloc_path).unwrap();
        let alloc = Allocation::parse(&text).unwrap();
        let c = Config::from_hf(std::path::Path::new(&ckpt)).unwrap();
        let expects = crate::deepseek::expected(&c).unwrap();
        let rows = budget(&expects, &alloc);
        let total: u64 = rows.iter().map(|r| r.bytes).sum();
        println!("allocation: {} tensors", alloc.len());
        for r in &rows {
            println!(
                "  {:14} {:6} tensors  {:8.1} GB",
                r.class,
                r.tensors,
                r.bytes as f64 / 1e9
            );
        }
        println!(
            "  {:14} {:6} tensors  {:8.1} GB",
            "TOTAL",
            rows.iter().map(|r| r.tensors).sum::<usize>(),
            total as f64 / 1e9
        );
        // The resident part is what the memory plan has to fit: everything except the Engram tables.
        let engram: u64 = rows.iter().filter(|r| r.class == "engram").map(|r| r.bytes).sum();
        println!("  resident (without engram): {:.1} GB", (total - engram) as f64 / 1e9);
    }
}
